"""LAMINADOR FALSO para pruebas y CI: imita la línea de comandos de un laminador tipo Orca/Anycubic Slicer Next
(`--datadir D --load-settings a.json;b.json --load-filaments f.json --export-3mf NOMBRE | --slice 0 --outputdir O [--no-check] archivo`) y escribe un gcode SINTÉTICO.

El gcode es una caja por objeto (perímetro `Outer wall` + zigzag `Sparse infill` por capa; soporte `Support` en una columna junto al objeto si `enable_support`), con cabecera y pie
estilo Orca (`; total layer number`, `; total filament used [g]`, `; estimated printing time (normal mode)`), `EXCLUDE_OBJECT_START` y temperaturas de inicio/fin. Es DETERMINISTA
(sin fechas) y diminuto. NO es un laminado: no calcula perímetros reales, puentes, soportes ni tiempos; las cifras son inventadas y no predicen ninguna impresión.

Choque de soportes simulado (para probar el reintento): con `AGENTCAD_FALSO_CHOQUE=1` falla (código 155, «gcode path conflicts») si hay >= 2 objetos, alguno con soporte, y el proceso
NO lleva `support_style = organic`; con `AGENTCAD_FALSO_CHOQUE=siempre` falla siempre que haya soporte. Uso: `python -m agentcad.laminador_falso ...`."""
import argparse, json, math, os, sys, zipfile
from pathlib import Path

ANCHO, R_FIL, DENSIDAD, VELOCIDAD, MAX_CAPAS = 0.45, 0.875, 1.27, 50.0, 400

def _e(longitud, alto): return longitud * ANCHO * alto / (math.pi * R_FIL ** 2)

def _cargar_json(lista):
    d = {}
    for f in [x for x in (lista or '').split(';') if x]:
        try: d.update(json.loads(Path(f).read_text(encoding='utf-8')))
        except (OSError, ValueError): pass
    return d

def _exportar_plantilla(a):
    """Imita `--export-3mf`: un zip con los ajustes cargados como `project_settings.config` (el laminador real escribe aquí el perfil completo)."""
    ajustes = _cargar_json(a.load_settings); ajustes.update(_cargar_json(a.load_filaments)); out = Path(a.outputdir); out.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out / a.export_3mf, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('Metadata/project_settings.config', json.dumps(ajustes, sort_keys=True)); z.writestr('3D/3dmodel.model', '<model/>')
    return 0

def _zigzag(x0, y0, x1, y1, densidad, z_idx):
    paso = max(3.0, ANCHO / max(densidad, 0.02)); n = max(1, min(12, int((y1 - y0) / paso))); ys = [y0 + (y1 - y0) * (i + 1) / (n + 1) for i in range(n)]
    pts = []
    for i, y in enumerate(ys): pts += [(x0, y), (x1, y)] if (i + z_idx) % 2 == 0 else [(x1, y), (x0, y)]
    return pts

def _capas(o, ajustes_globales):
    a = o['ajustes']; lh = float(a.get('layer_height', ajustes_globales.get('layer_height', '0.2')) or 0.2); zmax = float(o['bbox'][1][2])
    n = max(1, math.ceil(zmax / lh - 1e-9))
    if n > MAX_CAPAS: lh = zmax / MAX_CAPAS; n = MAX_CAPAS
    return lh, n

def _laminar(a):
    f = Path(a.archivo)
    if not f.is_file(): print(f'laminador_falso: no existe {f}', file=sys.stderr); return 2
    from .laminador import leer_3mf, _verdad
    with zipfile.ZipFile(f) as z: ajustes_g = json.loads(z.read('Metadata/project_settings.config').decode() or '{}') if 'Metadata/project_settings.config' in z.namelist() else {}
    objs = leer_3mf(f)
    if not objs: print('laminador_falso: el 3MF no contiene objetos', file=sys.stderr); return 2
    con_soporte = [o for o in objs if _verdad(o['ajustes'].get('enable_support', ajustes_g.get('enable_support', '0')))]
    choque = os.environ.get('AGENTCAD_FALSO_CHOQUE', '')
    if choque and con_soporte and ((choque == 'siempre') or (len(objs) >= 2 and str(ajustes_g.get('support_style', '')) != 'organic')):
        print(f'Error: gcode path conflicts found between objects {objs[0]["nombre"]} and {objs[-1]["nombre"]} (simulado por AGENTCAD_FALSO_CHOQUE)', file=sys.stderr); return 155
    por_z, vol_mm, longitud = {}, 0.0, 0.0
    for k, o in enumerate(objs):
        lh, n = _capas(o, ajustes_g); (x0, y0, _), (x1, y1, zmax) = o['bbox']; dens = float(str(o['ajustes'].get('sparse_infill_density', ajustes_g.get('sparse_infill_density', '15%'))).rstrip('%') or 15) / 100.0
        if dens > 1: dens /= 100.0
        sop = o in con_soporte; nombre = f'{o["nombre"]}_id_{k}_copy_0'
        for i in range(1, n + 1):
            z = round(min(i * lh, zmax) if i < n else zmax, 3); seg = []
            seg.append(('Outer wall', [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)]))
            seg.append(('Sparse infill', _zigzag(x0 + 0.5, y0 + 0.5, x1 - 0.5, y1 - 0.5, dens, i)))
            if sop and i <= max(1, int(n * 0.6)): sx = x1 + 0.6; sy = (y0 + y1) / 2; seg.append(('Support', [(sx, sy - 1.5), (sx + 2.0, sy - 1.5), (sx + 2.0, sy + 1.5), (sx, sy + 1.5), (sx, sy - 1.5)]))
            por_z.setdefault(z, []).append((nombre, lh, seg))
    L = ['; HEADER_BLOCK_START', '; generated by agentcad laminador_falso (SINTETICO: no es un laminado)', f'; total layer number: {len(por_z)}', f'; max_z_height: {max(por_z):.3f}',
         '; HEADER_BLOCK_END', 'M140 S75', 'M104 S240', 'G28', 'M109 S240', 'G90', 'G21', 'M83']
    for z in sorted(por_z):
        L += [';LAYER_CHANGE', f';Z:{z:.3f}']
        for nombre, lh, seg in por_z[z]:
            L += [f'EXCLUDE_OBJECT_START NAME={nombre}', f';HEIGHT:{lh:.3f}']
            for tipo, pts in seg:
                L += [f';TYPE:{tipo}', f';WIDTH:{ANCHO}', f'G1 Z{z:.3f} F600', f'G0 X{pts[0][0]:.3f} Y{pts[0][1]:.3f} F9000']
                for (xa, ya), (xb, yb) in zip(pts, pts[1:]):
                    d = math.hypot(xb - xa, yb - ya); longitud += d; vol_mm += _e(d, lh) * math.pi * R_FIL ** 2; L.append(f'G1 X{xb:.3f} Y{yb:.3f} E{_e(d, lh):.5f} F{int(VELOCIDAD * 60)}')
            L.append(f'EXCLUDE_OBJECT_END NAME={nombre}')
    cm3 = vol_mm / 1000.0; g = cm3 * DENSIDAD; seg_t = longitud / VELOCIDAD + 2.0 * len(por_z)
    h, r = divmod(int(round(seg_t)), 3600); m, s = divmod(r, 60)
    L += ['M104 S0', 'M140 S0', f'; filament used [mm] = {vol_mm / (math.pi * R_FIL ** 2):.2f}', f'; filament used [cm3] = {cm3:.2f}', f'; filament used [g] = {g:.2f}', f'; total filament used [g] = {g:.2f}',
          f'; estimated printing time (normal mode) = {h}h {m}m {s}s']
    out = Path(a.outputdir); out.mkdir(parents=True, exist_ok=True); (out / 'plate_1.gcode').write_text('\n'.join(L) + '\n', encoding='utf-8'); return 0

def main(argv=None):
    ap = argparse.ArgumentParser(prog='laminador_falso', description='Laminador falso (gcode sintético) para pruebas.')
    ap.add_argument('--datadir'); ap.add_argument('--load-settings'); ap.add_argument('--load-filaments'); ap.add_argument('--export-3mf'); ap.add_argument('--slice'); ap.add_argument('--outputdir', default='.')
    ap.add_argument('--no-check', action='store_true'); ap.add_argument('archivo', nargs='?')
    a = ap.parse_args(argv)
    if a.export_3mf: return _exportar_plantilla(a)
    if a.slice is not None and a.archivo: return _laminar(a)
    print('laminador_falso: use --export-3mf NOMBRE o --slice 0 <archivo.3mf>', file=sys.stderr); return 2

if __name__ == '__main__': sys.exit(main())
